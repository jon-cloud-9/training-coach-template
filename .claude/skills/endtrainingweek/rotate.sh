#!/usr/bin/env bash
# Rotate training weeks: keep the N most recent in weeks/, archive the rest,
# regenerate weeks/INDEX.md. Nothing is ever deleted.
#
# Usage:
#   rotate.sh                     # the active campaign (the one directory directly
#                                 # under campaigns/ that isn't archive/ or upcoming/)
#   rotate.sh <campaign-dir>      # a specific campaign, e.g. one just archived:
#                                 # rotate.sh campaigns/archive/spring-10k-2027
#
# Portable to bash 3.2 (macOS system bash) — no mapfile/readarray.
set -euo pipefail

KEEP="${KEEP:-4}"
ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

# read_into VARNAME < input  — one array element per line.
# Also sets <VARNAME>_N to the element count: bash 3.2 treats an empty array as
# unset under `set -u`, so ${#ARR[@]} on an empty array is a fatal error. Always
# test the count, and only index the array when the count is non-zero.
read_into() {
  local __name="$1" __line __n=0
  eval "$__name=()"
  while IFS= read -r __line; do
    [ -n "$__line" ] || continue
    eval "$__name+=(\"\$__line\")"
    __n=$(( __n + 1 ))
  done
  eval "${__name}_N=$__n"
}

if [ "$#" -ge 1 ]; then
  CAMPAIGN="${1%/}"
  if [ ! -d "$CAMPAIGN" ]; then
    echo "rotate: no such campaign directory: $CAMPAIGN" >&2
    exit 1
  fi
else
  # Active campaign = the only directory under campaigns/ that isn't archive/ or upcoming/.
  read_into CAMPAIGNS < <(find campaigns -mindepth 1 -maxdepth 1 -type d ! -name archive ! -name upcoming | sort)
  if [ "$CAMPAIGNS_N" -eq 0 ]; then
    echo "rotate: no active campaign under campaigns/ — nothing to do" >&2
    echo "rotate: promote the next one from campaigns/upcoming/ (see campaigns/upcoming/README.md)" >&2
    exit 0
  fi
  if [ "$CAMPAIGNS_N" -gt 1 ]; then
    echo "rotate: more than one active campaign found:" >&2
    printf '  %s\n' "${CAMPAIGNS[@]}" >&2
    echo "rotate: archive the finished one into campaigns/archive/, and keep future ones in campaigns/upcoming/" >&2
    exit 1
  fi
  CAMPAIGN="${CAMPAIGNS[0]}"
fi
WEEKS="$CAMPAIGN/weeks"
ARCHIVE="$WEEKS/archive"
mkdir -p "$ARCHIVE"

# Week folders sort correctly by name: week-NN-YYYY-MM-DD
read_into ALL < <(find "$WEEKS" -mindepth 1 -maxdepth 1 -type d ! -name archive -exec basename {} \; | sort)
TOTAL="$ALL_N"

MOVED=0
if [ "$TOTAL" -gt "$KEEP" ]; then
  CUT=$(( TOTAL - KEEP ))
  i=0
  while [ "$i" -lt "$CUT" ]; do
    wk="${ALL[$i]}"
    if git ls-files --error-unmatch "$WEEKS/$wk" >/dev/null 2>&1; then
      git mv "$WEEKS/$wk" "$ARCHIVE/$wk"
    else
      mv "$WEEKS/$wk" "$ARCHIVE/$wk"
    fi
    echo "rotate: archived $wk"
    MOVED=$(( MOVED + 1 ))
    i=$(( i + 1 ))
  done
fi

# Pull a display title from a week folder: prefer log.md's H1, fall back to plan.md's.
title_for() {
  local dir="$1" f h
  for f in "$dir/log.md" "$dir/plan.md"; do
    [ -f "$f" ] || continue
    h="$(grep -m1 '^# ' "$f" 2>/dev/null | sed 's/^# *//')" || true
    if [ -n "${h:-}" ]; then printf '%s' "$h"; return; fi
  done
  printf '%s' "$(basename "$dir")"
}

INDEX="$WEEKS/INDEX.md"
read_into ACTIVE < <(find "$WEEKS" -mindepth 1 -maxdepth 1 -type d ! -name archive -exec basename {} \; | sort -r)
read_into OLD    < <(find "$ARCHIVE" -mindepth 1 -maxdepth 1 -type d -exec basename {} \; 2>/dev/null | sort -r)
read_into LOOSE  < <(find "$ARCHIVE" -mindepth 1 -maxdepth 1 -type f -name '*.md' -exec basename {} \; 2>/dev/null | sort -r)

{
  echo "# Training Weeks"
  echo
  echo "_Regenerated by \`/endtrainingweek\`. Newest first._"
  echo
  echo "## Active (loaded by \`/starttrainingweek\`)"
  echo
  if [ "$ACTIVE_N" -eq 0 ]; then
    echo "_(none yet)_"
  else
    for wk in "${ACTIVE[@]}"; do
      echo "- [$(title_for "$WEEKS/$wk")]($wk/)"
    done
  fi
  echo
  echo "## Archived"
  echo
  if [ "$OLD_N" -eq 0 ] && [ "$LOOSE_N" -eq 0 ]; then
    echo "_(none yet)_"
  else
    [ "$OLD_N" -eq 0 ] || for wk in "${OLD[@]}"; do
      echo "- [$(title_for "$ARCHIVE/$wk")](archive/$wk/)"
    done
    [ "$LOOSE_N" -eq 0 ] || for f in "${LOOSE[@]}"; do
      h="$(grep -m1 '^# ' "$ARCHIVE/$f" 2>/dev/null | sed 's/^# *//')" || true
      echo "- [${h:-$f}](archive/$f) — predates the week format"
    done
  fi
} > "$INDEX"

echo "rotate: $TOTAL week folder(s), $MOVED archived, index written to $INDEX"
